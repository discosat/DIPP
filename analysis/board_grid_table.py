#!/usr/bin/env python3
"""LaTeX table of the board grid: utility within deadline per deadline pair,
cell and policy (seed 1), the final policy's regret against the best static
policy, and urgent hit rates.

    python3 analysis/board_grid_table.py analysis/board-grid/all -o analysis/board-grid/table_grid.tex

Inputs (explicit; missing ones are errors): <dir>/runs.csv (campaign_utility
on the board-grid runs) and analysis/eval_final/runs.csv (the P2 statics and
deadline-only, which the grid does not repeat).
"""
import argparse, csv, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POLS = ("low", "med", "high", "greedy", "final")
STATIC = ("low", "med", "high")
TIE = 0.02
PAIRS = [("P1", "20\\,s / 30\\,s"), ("P2", "20\\,s / 5\\,min"), ("P3", "60\\,s / 30\\,min"),
         ("E37P2", "20\\,s / 5\\,min"), ("E37P4", "5\\,min / 6\\,h")]
CELLS = {"C1": "1$\\times$ cloudy", "C2": "1$\\times$ Earth avg.", "C3": "1$\\times$ clear",
         "C4": "2$\\times$ Earth avg.", "C5": "2$\\times$ clear"}


def read(path):
    if not os.path.exists(path):
        raise SystemExit(f"missing input: {path}")
    return list(csv.DictReader(open(path)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dir")
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    u = {}
    for r in read(os.path.join(a.dir, "runs.csv")):
        if r["seed"] == "1":
            u[(r["cell"], r["policy"])] = r
    for r in read(os.path.join(ROOT, "analysis/eval_final/runs.csv")):
        if r["seed"] == "1" and r["policy"] in ("low", "med", "high", "greedy"):
            u.setdefault(("P2" + r["cell"], r["policy"]), r)
    lines = [
        "\\begin{tabular}{@{}llcccccrc@{}}",
        "\\toprule",
        "Deadlines (urgent / routine) & Cell & Low & Medium & High & Deadline-only & SIPP & Regret & Urgent \\\\",
        "\\midrule",
    ]
    for pair, label in PAIRS:
        cells = [c for c in CELLS if (pair + c, "final") in u]
        if not cells:
            raise SystemExit(f"no runs for {pair}")
        if pair.startswith("E37") and pair == "E37P2":
            lines.append("\\midrule")
            lines.append("\\multicolumn{9}{@{}l}{\\emph{Energy deficit: 3.7\\,W for the payload, board always on, "
                         "start 0.05\\,Wh above the floor}} \\\\")
        for i, c in enumerate(cells):
            k = pair + c
            row = {p: float(u[(k, p)]["U"]) for p in POLS if (k, p) in u}
            missing = [p for p in POLS if p not in row]
            if missing:
                raise SystemExit(f"{k}: missing {missing}")
            best = max(STATIC, key=row.get)
            reg = row[best] - row["final"]
            regs = f"{reg:+.3f}" if abs(reg) >= TIE else f"{reg:+.3f}$^\\dagger$"
            vals = []
            for p in POLS:
                s = f"{row[p]:.3f}"
                if p == best:
                    s = f"\\underline{{{s}}}"
                vals.append(s)
            urg = float(u[(k, "final")]["urgent_hit"])
            lines.append(f"{label if i == 0 else ''} & {CELLS[c]} & " + " & ".join(vals) +
                         f" & {regs} & {urg:.2f} \\\\")
        if pair in ("P1", "P2"):
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(a.o, "w").write("% GENERATED by analysis/board_grid_table.py -- do not edit.\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
