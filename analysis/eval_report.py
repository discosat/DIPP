#!/usr/bin/env python3
"""Results of the evaluation campaign for the paper (Section IV-E): Table VII
as LaTeX, utility per cell, and latency CDFs per class.

    python3 analysis/parse_runs.py runs/eval/* -o analysis/parsed/eval
    python3 analysis/campaign_utility.py analysis/parsed/eval -o analysis/eval
    python3 analysis/eval_report.py analysis/parsed/eval analysis/eval -o analysis/eval

Inputs are campaign_utility.py's runs.csv / cells.csv (seed-1 pairing, regret
against the best static policy, per METRIC.md) and parse_runs.py's
batches.csv (per-frame latency and deadline). Cells and policies missing from
the data are left out of the table and marked as missing on stdout, never
filled in. Writes table7.tex, U_by_cell.{pdf,png} and cdf_<cell>.{pdf,png}.
"""
import argparse, csv, os, sys
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

CELLS = [("C1", "1×, cloudy"), ("C2", "1×, Earth avg."), ("C3", "1×, clear sky"),
         ("C4", "2×, Earth avg."), ("C5", "2×, clear sky")]
POLICIES = [("low", "Static low"), ("med", "Static medium"), ("high", "Static high"),
            ("greedy", "Deadline-only"), ("adaptive-v1", "SIPP v1 (first revision)"), ("adaptive", "SIPP default")]
STATIC = ("low", "med", "high")
SURFACE, INK, INK2, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#8a8984", "#e6e5e0"
STYLE = {"low": ("#9db8d9", "v"), "med": ("#6f93c2", "s"), "high": ("#3d6aa8", "^"),
         "greedy": ("#eb6834", "D"), "adaptive-v1": ("#8a8984", "P"), "adaptive": ("#0b0b0b", "o")}


def fmt(v, nd=3):
    return "--" if v in (None, "") else f"{float(v):.{nd}f}"


def table7(cells, out):
    by = {(r["cell"], r["policy"]): r for r in cells}
    present = [c for c, _ in CELLS if any((c, p) in by for p, _ in POLICIES)]
    missing = [(c, p) for c in present for p, _ in POLICIES if (c, p) not in by]
    if missing:
        print("table7: missing (left blank):", ", ".join(f"{c}-{p}" for c, p in missing))
    lab = {c: l.replace("×", r"$\times$") for c, l in CELLS}
    lines = [r"\begin{table*}[t]", r"\centering",
             r"\caption{Utility within deadline $U$ per policy and cell (seed 1; best static policy in bold), "
             r"worst-case regret against the best static policy, and the deadline hit rate of urgent frames}",
             r"\label{tab:eval}",
             r"\begin{tabular}{@{}l" + "r" * len(present) + "r" + "r" * len(present) + r"@{}}",
             r"\toprule",
             " & \\multicolumn{%d}{c}{$U$} & Worst & \\multicolumn{%d}{c}{Urgent hit rate} \\\\" % (len(present), len(present)),
             r"\cmidrule(lr){2-%d}\cmidrule(lr){%d-%d}" % (len(present) + 1, len(present) + 3, 2 * len(present) + 2),
             "Policy & " + " & ".join(lab[c] for c in present) + " & regret & "
             + " & ".join(lab[c] for c in present) + r" \\",
             r"\midrule"]
    for p, name in POLICIES:
        if not any((c, p) in by for c in present):
            continue
        us, hs, regs = [], [], []
        for c in present:
            r = by.get((c, p))
            if r is None:
                us.append("--"); hs.append("--"); continue
            u = fmt(r["U_s1"])
            if p in STATIC and r.get("best_static") == p:
                u = r"\textbf{" + u + "}"
            us.append(u)
            hs.append(fmt(r["urgent_hit_s1"], 2))
            if r.get("regret_s1") not in (None, ""):
                regs.append(float(r["regret_s1"]))
        reg = fmt(max(regs)) if regs else "--"
        lines.append(f"{name} & " + " & ".join(us) + f" & {reg} & " + " & ".join(hs) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    with open(out, "w") as fh:
        fh.write("% GENERATED by analysis/eval_report.py -- do not edit.\n" + "\n".join(lines) + "\n")


def style_axes(ax):
    ax.set_facecolor(SURFACE)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    for sp in ("left", "bottom"):
        ax.spines[sp].set_color(MUTED)
    ax.tick_params(colors=INK2, labelsize=7.5)
    ax.grid(axis="y", color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def u_by_cell(cells, out):
    by = {(r["cell"], r["policy"]): r for r in cells}
    present = [(c, l) for c, l in CELLS if any((c, p) in by for p, _ in POLICIES)]
    fig, ax = plt.subplots(figsize=(3.5, 2.4))
    fig.patch.set_facecolor(SURFACE)
    style_axes(ax)
    n = len(POLICIES)
    for k, (p, name) in enumerate(POLICIES):
        xs, ys, lo, hi = [], [], [], []
        for i, (c, _) in enumerate(present):
            r = by.get((c, p))
            if r is None or r["U_s1"] in ("", None):
                continue
            x = i + (k - (n - 1) / 2) * 0.13
            xs.append(x); ys.append(float(r["U_s1"]))
            # seed spread where more than one seed exists
            if int(r.get("seeds") or 1) > 1:
                ax.vlines(x, float(r["U_min"]), float(r["U_max"]), color=STYLE[p][0], lw=1)
        col, mk = STYLE[p]
        ax.scatter(xs, ys, color=col, marker=mk, s=22 if p == "adaptive" else 16,
                   edgecolor=SURFACE, linewidth=0.5, zorder=3, label=name)
    ax.set_xticks(range(len(present)))
    ax.set_xticklabels([l.replace(", ", "\n") for _, l in present], fontsize=7, color=INK2)
    ax.set_ylabel("Utility within deadline, U", fontsize=8, color=INK2)
    ax.set_ylim(0, 1.02)
    leg = ax.legend(fontsize=6.5, frameon=False, loc="lower left", ncol=2)
    for t in leg.get_texts():
        t.set_color(INK)
    fig.savefig(out + ".pdf", bbox_inches="tight", facecolor=SURFACE)
    fig.savefig(out + ".png", bbox_inches="tight", facecolor=SURFACE, dpi=200)
    plt.close(fig)


def cdf(batches, cell, out):
    lat = defaultdict(lambda: defaultdict(list))        # policy -> class -> [latency / deadline]
    for b in batches:
        run = b["run_id"]
        parts = run.rsplit("-s", 1)
        if not parts[0].startswith(cell + "-") or not parts[1] == "1":
            continue
        p = parts[0][len(cell) + 1:]
        if p not in STYLE:
            continue
        slo = float(b["slo_s"]) if b.get("slo_s") else None
        if not slo:
            continue
        if b.get("completed") == "1" and b.get("latency_us"):
            lat[p][b["cls"]].append(int(b["latency_us"]) / 1e6 / slo)
        else:
            lat[p][b["cls"]].append(float("inf"))       # never completed: off the right edge
    if not lat:
        print(f"cdf: no seed-1 runs for {cell}")
        return
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.3), sharey=True)
    fig.patch.set_facecolor(SURFACE)
    for ax, cls, title in ((axes[0], "urgent", "Urgent (deadline 20 s)"), (axes[1], "routine", "Routine (deadline 300 s)")):
        style_axes(ax)
        ax.axvline(1.0, color=MUTED, lw=0.8, ls=(0, (3, 3)))
        for p, name in POLICIES:
            v = sorted(lat[p][cls]) if p in lat else []
            if not v:
                continue
            ys = [(i + 1) / len(v) for i in range(len(v))]
            col, _ = STYLE[p]
            ax.step(v, ys, where="post", color=col, lw=1.6 if p == "adaptive" else 1.1, label=name)
        ax.set_xscale("log")
        ax.set_title(title, fontsize=8, color=INK)
        ax.set_xlabel("Latency / deadline", fontsize=8, color=INK2)
    axes[0].set_ylabel("Fraction of frames", fontsize=8, color=INK2)
    leg = fig.legend(*axes[1].get_legend_handles_labels(), fontsize=6.5, frameon=False, loc="lower center",
                     ncol=5, bbox_to_anchor=(0.5, -0.12))
    for t in leg.get_texts():
        t.set_color(INK)
    fig.savefig(out + ".pdf", bbox_inches="tight", facecolor=SURFACE)
    fig.savefig(out + ".png", bbox_inches="tight", facecolor=SURFACE, dpi=200)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("parsed_dir")
    ap.add_argument("util_dir")
    ap.add_argument("-o", "--outdir", required=True)
    ap.add_argument("--cdf-cells", default="C3,C4", help="cells to draw latency CDFs for")
    a = ap.parse_args()
    cells = list(csv.DictReader(open(os.path.join(a.util_dir, "cells.csv"))))
    batches = list(csv.DictReader(open(os.path.join(a.parsed_dir, "batches.csv"))))
    os.makedirs(a.outdir, exist_ok=True)
    table7(cells, os.path.join(a.outdir, "table7.tex"))
    u_by_cell(cells, os.path.join(a.outdir, "U_by_cell"))
    for c in a.cdf_cells.split(","):
        cdf(batches, c, os.path.join(a.outdir, f"cdf_{c}"))
    print(f"wrote {a.outdir}/table7.tex, U_by_cell.pdf, cdf_*.pdf")
    return 0


if __name__ == "__main__":
    sys.exit(main())
