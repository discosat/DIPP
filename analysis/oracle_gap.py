#!/usr/bin/env python3
"""Frame-by-frame comparison of the oracle's schedule with SIPP's (simulation):
where does the gap U_oracle - U_sipp come from? Exact decomposition per (cell, seed):

  under-effort  frames on time in both, SIPP at lower quality (split per stage)
  lateness      frames on time for the oracle, late or never finished in SIPP
  triage        frames on time in SIPP that the oracle does not deliver on time

    python3 analysis/oracle_gap.py -o analysis/lab

Reads oracle_combos.csv / oracle_results.csv (analysis/oracle.py run); only (cell, seed)
with an OPTIMAL integer oracle solution (the LP-only cells have no per-frame schedule).
"""
import argparse, collections, csv, os, statistics, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, HERE)
import policy_lab as L  # noqa: E402
from predict_board_grid import build_scenario  # noqa: E402
from oracle import grid_runs, sipp_policy, STAGES  # noqa: E402


def q_of(eff):
    return sum(L.QUAL[s][eff[s]] for s in STAGES) / 3.0


def analyse(cell, sd, r, orc):
    sc = build_scenario(r)[0]
    sc["record"] = []
    out = L.simulate(sc, sipp_policy())
    N = len(sc["arrivals"])
    o = {int(x["frame"]): x for x in orc}
    row = collections.Counter()
    per_stage = collections.Counter()
    late_eff = collections.Counter()
    for i, (arr, dl, done, cls, eff) in enumerate(out["frames"]):
        on_s = done is not None and done <= dl + 1e-9
        x = o[i]
        on_o = x["on_time"] == "1"
        qo = q_of({s: x[s] for s in STAGES}) if on_o else 0.0
        qs = q_of(eff) if on_s else 0.0
        if on_o and on_s:
            row["under_effort"] += qo - qs
            for s in STAGES:
                per_stage[s] += (L.QUAL[s][x[s]] - L.QUAL[s][eff[s]]) / 3.0
            row["n_both"] += 1
        elif on_o:
            row["lateness"] += qo
            row["n_late_" + cls] += 1
            row["n_late_unfinished" if done is None else "n_late_finished"] += 1
            if done is not None and all(s in eff for s in STAGES):
                late_eff["/".join(eff[s] for s in STAGES)] += 1
        elif on_s:
            row["triage"] -= qs
            row["n_triage"] += 1
    gap = sum(row[k] for k in ("under_effort", "lateness", "triage")) / N
    u_o = sum(q_of({s: o[i][s] for s in STAGES}) for i in range(N) if o[i]["on_time"] == "1") / N
    assert abs((u_o - out["U"]) - gap) < 1e-9, (cell, sd, u_o, out["U"], gap)
    res = {"cell": cell, "seed": sd, "N": N, "U_oracle": u_o, "U_sipp": out["U"], "gap": gap,
           "under_effort": row["under_effort"] / N, "lateness": row["lateness"] / N, "triage": row["triage"] / N,
           **{f"ue_{s}": per_stage[s] / N for s in STAGES},
           "n_late_urgent": row["n_late_urgent"], "n_late_routine": row["n_late_routine"],
           "n_late_unfinished": row["n_late_unfinished"], "n_triage": row["n_triage"],
           "cap_dropped": out["cap_dropped"], "late_eff": dict(late_eff)}
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    rd = lambda f: list(csv.DictReader(open(os.path.join(a.o, f))))
    ok = {(r["cell"], int(r["seed"])) for r in rd("oracle_results.csv") if r["status"] == "OPTIMAL"}
    combos = collections.defaultdict(list)
    for x in rd("oracle_combos.csv"):
        combos[(x["cell"], int(x["seed"]))].append(x)
    rows = [analyse(c, s, r, combos[(c, s)]) for c, s, r in grid_runs([1, 2, 3]) if (c, s) in ok]
    with open(os.path.join(a.o, "oracle_gap.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=[k for k in rows[0] if k != "late_eff"])
        w.writeheader(); w.writerows([{k: v for k, v in x.items() if k != "late_eff"} for x in rows])
    cells = sorted({x["cell"] for x in rows})
    m = lambda c, k: statistics.mean(x[k] for x in rows if x["cell"] == c)
    sm = lambda c, k: sum(x[k] for x in rows if x["cell"] == c)
    L_ = ["# Where SIPP loses against the oracle (simulation, hard deadlines)", "",
          "Generated by `analysis/oracle_gap.py`. Exact decomposition of U_oracle − U_sipp (means over seeds;",
          "cells with an OPTIMAL integer oracle solution). The oracle is the relaxed optimum (preemption, free order,",
          "skipping, no queue cap), so part of each gap is unreachable for any non-preemptive EDF policy.", "",
          "| cell | U oracle | U SIPP | gap | under-effort (cls / seg / enc) | lateness | triage | late frames urgent / routine (unfinished) | oracle-skipped frames SIPP delivered |",
          "|---|---|---|---|---|---|---|---|---|"]
    for c in cells:
        L_.append(f"| {c} | {m(c, 'U_oracle'):.3f} | {m(c, 'U_sipp'):.3f} | {m(c, 'gap'):.3f} | "
                  f"{m(c, 'under_effort'):.3f} ({m(c, 'ue_cls'):.3f} / {m(c, 'ue_seg'):.3f} / {m(c, 'ue_enc'):.3f}) | "
                  f"{m(c, 'lateness'):.3f} | {m(c, 'triage'):.3f} | {sm(c, 'n_late_urgent')} / {sm(c, 'n_late_routine')} "
                  f"({sm(c, 'n_late_unfinished')}) | {sm(c, 'n_triage')} |")
    L_ += ["", "Late frames (SIPP finished them, but after the deadline) by the effort SIPP used:", ""]
    for c in cells:
        le = collections.Counter()
        for x in rows:
            if x["cell"] == c:
                le.update(x["late_eff"])
        if le:
            L_.append(f"- {c}: " + ", ".join(f"{k} {v}" for k, v in le.most_common(4)))
    open(os.path.join(a.o, "oracle_gap.md"), "w").write("\n".join(L_) + "\n")
    print("\n".join(L_))


if __name__ == "__main__":
    main()
