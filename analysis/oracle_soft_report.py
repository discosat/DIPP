#!/usr/bin/env python3
"""Soft vs hard deadlines: the oracle bound, SIPP and the two fixed designs an operator
would choose (one combination for every content mix: the highest-quality combination
whose frame time fits the nominal 6.68 s frame period on Earth-average content, resp. on
clear-sky content -- chosen from the cost model, not from U).

    ~/.venvs/dipp-oracle/bin/python analysis/oracle_soft_report.py -o analysis/lab
"""
import argparse, collections, csv, multiprocessing as mp, os, statistics, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, HERE)
import policy_lab as L  # noqa: E402
from predict_board_grid import build_scenario  # noqa: E402
from oracle import grid_runs, soft_value, SOFT_VARIANTS, STAGES  # noqa: E402

DESIGNS = {"avg-design": ("high", "med", "high"), "worst-design": ("med", "med", "low")}
TIE = 0.02


def one(job):
    cell, sd, r = job
    out = []
    for dn, cmb in DESIGNS.items():
        sc = build_scenario(r)[0]; sc["record"] = []
        N = len(sc["arrivals"])
        res = L.simulate(sc, L.FixedAssignment({(i, s): cmb[k] for i in range(N) for k, s in enumerate(STAGES)}, gran="batch"))
        row = {"cell": cell, "seed": sd, "design": dn, "U": res["U"]}
        for name, G, uh in SOFT_VARIANTS:
            row[name] = soft_value(sc, res["frames"], G, uh)
        out.append(row)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    with mp.Pool(7) as pool:
        des = [x for xs in pool.map(one, grid_runs([1, 2, 3])) for x in xs]
    rd = lambda f: list(csv.DictReader(open(os.path.join(a.o, f))))
    soft = {(r["cell"], int(r["seed"]), r["variant"]): r for r in rd("oracle_soft.csv")}
    res = {(r["cell"], int(r["seed"])): r for r in rd("oracle_results.csv")}
    lp = {(r["cell"], int(r["seed"])): float(r["UB_LP"]) for r in rd("oracle_lp.csv")}
    D = {(x["cell"], x["seed"], x["design"]): x for x in des}
    fl = lambda v: float(v) if v not in ("", "nan") else float("inf")
    cells = sorted({k[0] for k in res})
    sd = (1, 2, 3)
    mean = lambda f: statistics.mean(f(s) for s in sd)
    L_ = ["# Soft vs hard deadlines — oracle bound, SIPP, fixed designs (simulation)", "",
          "Generated by `analysis/oracle_soft_report.py`. Means over seeds 1-3. V_G as METRIC.md 2026-10-15",
          "(late frame keeps q·max(0, 1 − late/(G·D))); G1uh = urgent frames hard. Hard = U (G = 0).",
          "UB: upper bound (LP; * = not converged in 1800 s: valid but possibly loose).",
          "Fixed designs: one combination for every content mix, chosen from the cost model (fits the 6.68 s",
          f"frame period on Earth-average / clear-sky content): avg-design {'/'.join(DESIGNS['avg-design'])}, "
          f"worst-design {'/'.join(DESIGNS['worst-design'])}.", ""]
    for name in ("hard",) + tuple(v[0] for v in SOFT_VARIANTS):
        L_ += [f"## {name}", "", "| cell | UB | SIPP | gap UB − SIPP | avg-design | worst-design | SIPP − avg | SIPP − worst |",
               "|---|---|---|---|---|---|---|---|"]
        tally = collections.Counter()
        for c in cells:
            if name == "hard":
                ub = mean(lambda s: min(lp[(c, s)], fl(res[(c, s)]["UB"])))
                conv = True
                vs = mean(lambda s: float(res[(c, s)]["U_sipp"]))
                va = mean(lambda s: D[(c, s, "avg-design")]["U"])
                vw = mean(lambda s: D[(c, s, "worst-design")]["U"])
            else:
                ub = mean(lambda s: float(soft[(c, s, name)]["UB_soft"]))
                conv = all(soft[(c, s, name)]["converged"] == "True" for s in sd)
                vs = mean(lambda s: float(soft[(c, s, name)]["V_sipp"]))
                va = mean(lambda s: D[(c, s, "avg-design")][name])
                vw = mean(lambda s: D[(c, s, "worst-design")][name])
            for k, v in (("avg", vs - va), ("worst", vs - vw)):
                tally[(k, "W" if v > TIE else "L" if v < -TIE else "T")] += 1
            L_.append(f"| {c} | {ub:.3f}{'' if conv else '*'} | {vs:.3f} | {ub - vs:.3f} | {va:.3f} | {vw:.3f} | "
                      f"{vs - va:+.3f} | {vs - vw:+.3f} |")
        L_ += ["", f"SIPP vs avg-design W/T/L {tally[('avg', 'W')]}/{tally[('avg', 'T')]}/{tally[('avg', 'L')]}; "
                   f"vs worst-design {tally[('worst', 'W')]}/{tally[('worst', 'T')]}/{tally[('worst', 'L')]}.", ""]
    open(os.path.join(a.o, "oracle_soft_summary.md"), "w").write("\n".join(L_) + "\n")
    print("\n".join(L_))


if __name__ == "__main__":
    main()
