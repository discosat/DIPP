#!/usr/bin/env python3
"""SIPP over a ladder of per-stage effort combinations vs the frozen SIPP, on the
board-grid cells in simulation, against the oracle's references.
Protocol: analysis/lab/ladder_protocol.md.

    python3 analysis/sim_ladder.py -o analysis/lab
    python3 analysis/sim_ladder.py -o analysis/lab --ksweep
    python3 analysis/sim_ladder.py -o analysis/lab --stress
"""
import argparse, csv, multiprocessing as mp, os, statistics, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, HERE)
import policy_lab as L  # noqa: E402
from predict_board_grid import build_scenario  # noqa: E402
from oracle import grid_runs  # noqa: E402

TIE = 0.02


def one(job):
    cell, sd, r = job
    out = []
    for pol in L.policy_set("ladder"):
        res = L.simulate(build_scenario(r)[0], pol)
        out.append({"cell": cell, "seed": sd, "policy": pol.name, "U": res["U"],
                    "urgent_hit": res["urgent_hit"], "routine_hit": res["routine_hit"],
                    "dropped": res["dropped"], "cap_dropped": res["cap_dropped"]})
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", required=True)
    ap.add_argument("--ksweep", action="store_true")
    ap.add_argument("--stress", action="store_true")
    a = ap.parse_args()
    if a.ksweep:
        return ksweep(a)
    if a.stress:
        return stress(a)
    jobs = grid_runs([1, 2, 3])
    with mp.Pool(7) as pool:
        rows = [x for xs in pool.map(one, jobs) for x in xs]
    with open(os.path.join(a.o, "ladder_results.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)

    U = {(x["cell"], x["seed"], x["policy"]): x for x in rows}
    # regression: uniform rungs == sipp exactly
    bad = [(c, s) for (c, s, p) in U if p == "sipp"
           and any(U[(c, s, "sipp")][k] != U[(c, s, "sipp-rungs-uniform")][k] for k in ("U", "urgent_hit", "routine_hit"))]
    rd = lambda f: {(r["cell"], int(r["seed"])): r for r in csv.DictReader(open(os.path.join(a.o, f)))}
    orc, lp = rd("oracle_results.csv"), rd("oracle_lp.csv")
    f = lambda x: float(x) if x not in ("", "nan") else float("nan")
    cells = sorted({c for c, _, _ in U})
    L_ = ["# SIPP over a per-stage effort ladder — simulation results", "",
          "Protocol: ladder_protocol.md. Generated by `analysis/sim_ladder.py`. Means over seeds 1-3.",
          "UB / achievable / best27 / best uniform from the oracle (oracle_summary.md).", "",
          "Regression (uniform rungs == frozen SIPP in every cell and seed): "
          + ("OK" if not bad else f"FAILED in {bad}"), "",
          "| cell | UB | achievable | best27 | best uniform | SIPP | SIPP-ladder | Δ (ladder − SIPP) | ladder − best27 | urgent hit SIPP / ladder |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    wins = ties = losses = 0
    for c in cells:
        sd = [1, 2, 3]
        m = lambda p, k="U": statistics.mean(U[(c, s, p)][k] for s in sd)
        ub = statistics.mean(min(v for v in (f(orc[(c, s)]["UB"]), f(lp[(c, s)]["UB_LP"])) if v == v) for s in sd)
        b27 = statistics.mean(f(orc[(c, s)]["best27_static_U"]) for s in sd)
        ach = statistics.mean(max(v for v in (f(orc[(c, s)]["U_replay"]), f(orc[(c, s)]["best27_static_U"])) if v == v) for s in sd)
        buni = statistics.mean(f(orc[(c, s)]["best_uniform_static_U"]) for s in sd)
        us, ul = m("sipp"), m("sipp-ladder")
        d = ul - us
        wins += d > TIE; ties += abs(d) <= TIE; losses += d < -TIE
        L_.append(f"| {c} | {ub:.3f} | {ach:.3f} | {b27:.3f} | {buni:.3f} | {us:.3f} | {ul:.3f} | {d:+.3f} | "
                  f"{ul - b27:+.3f} | {m('sipp', 'urgent_hit'):.2f} / {m('sipp-ladder', 'urgent_hit'):.2f} |")
    L_ += ["", f"Ladder vs SIPP: {wins} wins, {ties} ties, {losses} losses (|Δ| ≤ {TIE} = tie)."]
    open(os.path.join(a.o, "ladder_summary.md"), "w").write("\n".join(L_) + "\n")
    print("\n".join(L_))

KS = (1.0, 1.25, 1.5, 1.75, 2.0, 2.5, 3.0)


def ksweep_policies():
    vb = dict(guard="hist", accept="feas", boundary="backlog", cad_src="arrival", budget="frames")
    out = []
    for k in KS:
        fin = dict(vb, k=k, path_k=k, cap_budget=True, nohist="fill", energy_time=True)
        out += [(f"sipp", k, L.Ladder(**fin, name=f"sipp-k{k}")),
                (f"sipp-ladder", k, L.RungLadder(rungs="pareto", **fin, name=f"sipp-ladder-k{k}"))]
    return out


def one_k(job):
    cell, sd, r = job
    out = []
    for pname, k, pol in ksweep_policies():
        res = L.simulate(build_scenario(r)[0], pol)
        out.append({"cell": cell, "seed": sd, "policy": pname, "k": k, "U": res["U"],
                    "urgent_hit": res["urgent_hit"], "routine_hit": res["routine_hit"],
                    "dropped": res["dropped"], "cap_dropped": res["cap_dropped"]})
    return out


def ksweep(a):
    with mp.Pool(7) as pool:
        rows = [x for xs in pool.map(one_k, grid_runs([1, 2, 3])) for x in xs]
    with open(os.path.join(a.o, "ladder_ksweep.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    rd = lambda f: {(r["cell"], int(r["seed"])): r for r in csv.DictReader(open(os.path.join(a.o, f)))}
    orc = rd("oracle_results.csv")
    fl = lambda x: float(x) if x not in ("", "nan") else float("nan")
    cells = sorted({x["cell"] for x in rows})
    cm = {}                                              # (policy, k, cell) -> means over seeds
    for pname in ("sipp", "sipp-ladder"):
        for k in KS:
            for c in cells:
                xs = [x for x in rows if x["policy"] == pname and x["k"] == k and x["cell"] == c]
                cm[(pname, k, c)] = {m: statistics.mean(x[m] for x in xs) for m in ("U", "urgent_hit", "dropped")}
    ref = {c: statistics.mean(fl(orc[(c, s)]["best27_static_U"]) for s in (1, 2, 3)) for c in cells}
    uni = {c: statistics.mean(fl(orc[(c, s)]["best_uniform_static_U"]) for s in (1, 2, 3)) for c in cells}
    base = {c: cm[("sipp", 2.0, c)]["U"] for c in cells}
    L_ = ["# Safety factor k: sweep for SIPP (uniform efforts) and SIPP-ladder (Pareto rungs) — simulation", "",
          "Protocol: ladder_protocol.md (addendum 2026-11-01). Means over seeds 1-3, 17 board-grid cells.",
          "vs frozen = against sipp at k = 2 (W/T/L, |ΔU| ≤ 0.02 tie); gap = policy − reference (negative: below it).", "",
          "| policy | k | mean U | W/T/L vs frozen | worst Δ vs frozen (cell) | mean gap best27 | worst gap best27 (cell) | worst gap best uniform (cell) | min urgent hit (cell) | dropped / run |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for pname in ("sipp", "sipp-ladder"):
        for k in KS:
            U = {c: cm[(pname, k, c)]["U"] for c in cells}
            d = {c: U[c] - base[c] for c in cells}
            w_ = sum(v > TIE for v in d.values()); l_ = sum(v < -TIE for v in d.values())
            wc = min(cells, key=lambda c: d[c])
            g27 = {c: U[c] - ref[c] for c in cells}; gu = {c: U[c] - uni[c] for c in cells}
            c27, cu = min(cells, key=lambda c: g27[c]), min(cells, key=lambda c: gu[c])
            uh = {c: cm[(pname, k, c)]["urgent_hit"] for c in cells}
            cuh = min(cells, key=lambda c: uh[c])
            drop = statistics.mean(cm[(pname, k, c)]["dropped"] for c in cells)
            L_.append(f"| {pname} | {k} | {statistics.mean(U.values()):.3f} | {w_}/{len(cells) - w_ - l_}/{l_} | "
                      f"{d[wc]:+.3f} ({wc}) | {statistics.mean(g27.values()):+.3f} | {g27[c27]:+.3f} ({c27}) | "
                      f"{gu[cu]:+.3f} ({cu}) | {uh[cuh]:.2f} ({cuh}) | {drop:.1f} |")
    L_ += ["", "## U per cell (k columns; S = sipp, L = sipp-ladder)", "",
           "| cell | best27 | " + " | ".join(f"S {k} | L {k}" for k in KS) + " |",
           "|---|---|" + "---|---|" * len(KS)]
    for c in cells:
        L_.append(f"| {c} | {ref[c]:.3f} | " + " | ".join(f"{cm[('sipp', k, c)]['U']:.3f} | {cm[('sipp-ladder', k, c)]['U']:.3f}" for k in KS) + " |")
    open(os.path.join(a.o, "ladder_ksweep.md"), "w").write("\n".join(L_) + "\n")
    print("\n".join(L_))

STRESS = {"nominal": (0.0, 0.0, None), "jitter0.15": (0.15, 0.0, None), "model0.3": (0.0, 0.3, None),
          "both": (0.15, 0.3, None), "optimistic0.8": (0.0, 0.0, 0.8)}
KS_STRESS = (1.25, 1.5, 1.75, 2.0)


def stressed(r, name, cell, sd):
    import math, random
    from lab_real import stable_seed
    jit, me, bias = STRESS[name]
    sc = build_scenario(r)[0]
    sc["jitter"] = jit
    if me:
        rng = random.Random(stable_seed("modelerr", cell, sd))
        sc["model"] = L.ModelCost(sc["cost"], {sl: math.exp(rng.gauss(0, me)) for sl in range(1, 21)})
    if bias:
        sc["model"] = L.ModelCost(sc["cost"], {sl: bias for sl in range(1, 21)})
    return sc


def one_s(job):
    cell, sd, r = job
    vb = dict(guard="hist", accept="feas", boundary="backlog", cad_src="arrival", budget="frames")
    out = []
    for name in STRESS:
        for k in KS_STRESS:
            fin = dict(vb, k=k, path_k=k, cap_budget=True, nohist="fill", energy_time=True)
            for pname, pol in (("sipp", L.Ladder(**fin, name="s")), ("sipp-ladder", L.RungLadder(rungs="pareto", **fin, name="l"))):
                res = L.simulate(stressed(r, name, cell, sd), pol)
                urg = sum(1 for a in build_scenario(r)[0]["arrivals"] if a[2] == "urgent")
                out.append({"stress": name, "cell": cell, "seed": sd, "policy": pname, "k": k, "U": res["U"],
                            "urgent_hit": res["urgent_hit"], "urgent_miss": round((1 - res["urgent_hit"]) * urg),
                            "dropped": res["dropped"]})
    return out


def stress(a):
    with mp.Pool(7) as pool:
        rows = [x for xs in pool.map(one_s, grid_runs([1, 2, 3])) for x in xs]
    with open(os.path.join(a.o, "ladder_stress.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    cells = sorted({x["cell"] for x in rows})
    g = {}
    for x in rows:
        g.setdefault((x["stress"], x["policy"], x["k"], x["cell"]), []).append(x)
    mean = lambda st_, p, k, c, m: statistics.mean(x[m] for x in g[(st_, p, k, c)])
    tot = lambda st_, p, k, m: sum(x[m] for c in cells for x in g[(st_, p, k, c)])
    L_ = ["# Lower k under stress (jitter, cost-model error) — simulation", "",
          "Protocol: ladder_protocol.md (addendum: stress test). Means over seeds 1-3, 17 cells.",
          "Δ vs frozen = against sipp at k = 2 under the same stress; tie |Δ| ≤ 0.02.",
          "Urgent hit: lowest over cells excluding P1C5 (infeasible for every policy).", ""]
    verdict = {}
    for st_ in STRESS:
        L_ += [f"## {st_}", "",
               "| policy | k | mean U | W/T/L vs frozen | worst Δ (cell) | min urgent hit (cell) | urgent misses | dropped |",
               "|---|---|---|---|---|---|---|---|"]
        for p in ("sipp", "sipp-ladder"):
            for k in KS_STRESS:
                d = {c: mean(st_, p, k, c, "U") - mean(st_, "sipp", 2.0, c, "U") for c in cells}
                w_ = sum(v > TIE for v in d.values()); l_ = sum(v < -TIE for v in d.values())
                wc = min(cells, key=lambda c: d[c])
                uh = {c: mean(st_, p, k, c, "urgent_hit") for c in cells if c != "P1C5"}
                cu = min(uh, key=uh.get)
                uh0 = min(mean(st_, "sipp", 2.0, c, "urgent_hit") for c in cells if c != "P1C5")
                ok = l_ == 0 and uh[cu] >= uh0 - 1e-9
                verdict.setdefault((p, k), []).append(ok)
                L_.append(f"| {p} | {k} | {statistics.mean(mean(st_, p, k, c, 'U') for c in cells):.3f} | {w_}/{len(cells) - w_ - l_}/{l_} | "
                          f"{d[wc]:+.3f} ({wc}) | {uh[cu]:.3f} ({cu}) | {tot(st_, p, k, 'urgent_miss')} | {tot(st_, p, k, 'dropped')} |")
        L_.append("")
    L_ += ["## Decision rule (no loss beyond the tie line in any cell, no lower urgent hit, at every stress level)", ""]
    for (p, k), oks in verdict.items():
        L_.append(f"- {p} k={k}: " + ("PASSES" if all(oks) else "fails at " + ", ".join(s_ for s_, ok in zip(STRESS, oks) if not ok)))
    open(os.path.join(a.o, "ladder_stress.md"), "w").write("\n".join(L_) + "\n")
    print("\n".join(L_))


if __name__ == "__main__":
    main()
