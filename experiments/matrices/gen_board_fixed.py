#!/usr/bin/env python3
"""Board check of the two fixed designs (2026-11-02): one effort combination for
every content mix, chosen from the cost model (highest-quality combination whose
frame time fits the 6.68 s period on Earth-average / clear-sky content):

  avg    high/med/high   pipeline 4 in manifest_fixed_designs.yaml
  worst  med/med/low     pipeline 5 in manifest_fixed_designs.yaml

Simulated in analysis/oracle_soft_report.py; the simulator is pessimistic for
overloaded static policies (board-grid/SUMMARY.md), which is where these designs
collapse, so their collapse cells and their best cells against SIPP are re-run on
the board. Needs staging/s5a-final7 deployed (s5a-final6 + that manifest). Same
scenario construction as the board grid (gen_board_grid.run), seed 1.
Protocol and predictions: analysis/lab/fixed_designs_board_protocol.md.
"""
import os, sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_eval as G  # noqa: E402
import gen_board_grid as B  # noqa: E402

DESIGNS = {"avg": 4, "worst": 5}
RUNS = [("P1", "C3", "avg", False), ("P1", "C4", "avg", False), ("P2", "C5", "avg", False),
        ("P2", "C3", "avg", True), ("P2", "C4", "avg", False),
        ("P1", "C4", "worst", False), ("P2", "C5", "worst", False), ("P3", "C5", "worst", False),
        # 2026-11-05: frame times on cloudy content for the frame-time figure (F5)
        ("P2", "C1", "avg", False), ("P2", "C1", "worst", False)]


def run(pair, cell, design, deficit):
    r = B.run(pair, cell, "low", 1, deficit=deficit)          # scenario as the grid; policy replaced below
    r["label"] = r["label"].replace("-low-", f"-{design}-")
    r["pipeline"] = DESIGNS[design]
    return r


def main():
    runs = [run(*x) for x in RUNS]
    m = {"run_set": "board-fixed", "defaults": dict(G.COMMON), "runs": runs}
    out = os.path.join(HERE, "board-fixed.yaml")
    with open(out, "w") as fh:
        fh.write("# GENERATED by experiments/matrices/gen_board_fixed.py -- do not edit.\n")
        yaml.safe_dump(m, fh, sort_keys=False)
    print(f"wrote {out}: {len(runs)} runs")


if __name__ == "__main__":
    main()
