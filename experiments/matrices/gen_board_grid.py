#!/usr/bin/env python3
"""Board grid for the final policy (2026-10-14): paired deadlines, the final
policy against the static policies and deadline-only selection. No ablations.

    python3 experiments/matrices/gen_board_grid.py   -> experiments/matrices/board-grid.yaml

Deadline pairs (urgent, routine), each a cited mission type:
  P1 (20 s, 30 s)     keep-up (Kodan), every frame almost urgent
  P2 (20 s, 300 s)    alert products (Phoenix); the board evaluation's pair
  P3 (60 s, 1800 s)   onboard decision (Dynamic Targeting) + alert (CleanSeaNet)
  P4 (300 s, 21600 s) store-and-forward science with alerts (DISCO-2 contact)

Blocks, in run order (an early stop leaves complete blocks):
  A  final policy at P2, C1-C5 x seeds 1-3 (static / deadline-only at P2 are
     the board evaluation's runs, whose code path did not change)
  B  P1, P3, P4 x C2-C5 x {low, med, high, deadline-only, final}, seed 1
  C  final policy, seeds 2-3, at P1, P3, P4 x C3, C5
  D  energy deficit (platform dawndusk-3w7: continuous sun, 3.7 W for the
     payload, board always on, start 0.05 Wh above the floor) x P2, P4 x
     C2, C3 x the five policies, seed 1
Labels: <pair><cell>-<policy>-s<seed>; block D prefixes E37.
"""
import os, sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import gen_eval as G  # noqa: E402

PAIRS = {"P1": (20, 30), "P2": (20, 300), "P3": (60, 1800), "P4": (300, 21600)}
POLICIES = {"low": "low", "med": "med", "high": "high", "greedy": "greedy", "final": "adaptive"}
DEFICIT_PLATFORM = "dawndusk-3w7.env"


def trace(pair, load, seed):
    stem = "main" if load == "1x" else "main2x"
    return f"{G.TR}/{stem}-s{seed}.trace" if pair == "P2" else f"{G.TR}/{stem}-{pair}-s{seed}.trace"


def floor_soc(platform, above_wh):
    env = G.mat.read_env(os.path.join(ROOT, "experiments/platforms", platform))
    cap = float(env["DIPP_BATT_CAPACITY_WH"])
    floor = float(env["DIPP_BATT_SURVIVAL_ORBITS"]) * float(env["DIPP_BATT_BUS_W"]) * \
        float(env["DIPP_BATT_ORBIT_MIN"]) / 60.0
    return round((floor + above_wh) / cap, 5)


def run(pair, cell, policy, seed, deficit=False):
    load, content = G.CELLS[cell]
    tr = trace(pair, load, seed)
    ph = G.header(tr, "phase0")
    prefix = ("E37" if deficit else "") + pair + cell
    r = {"label": f"{prefix}-{policy}-s{seed}", "arrivals": tr, "image_prefix": G.CONTENT[content],
         "phase0": round(ph, 4)}
    if deficit:
        r["platform"] = DEFICIT_PLATFORM
        r["soc0"] = floor_soc(DEFICIT_PLATFORM, 0.05)
    else:
        r["soc0"] = G.steady("disco2-bol.env", ph)
    r.update(G.POL[POLICIES[policy]])
    return r


def main():
    runs = []
    runs += [run("P2", c, "final", s) for c in ("C1", "C2", "C3", "C4", "C5") for s in (1, 2, 3)]          # A
    for pair in ("P1", "P3", "P4"):                                                                       # B
        runs += [run(pair, c, p, 1) for c in ("C2", "C3", "C4", "C5") for p in POLICIES]
    runs += [run(pair, c, "final", s) for pair in ("P1", "P3", "P4") for c in ("C3", "C5") for s in (2, 3)]  # C
    runs += [run(pair, c, p, 1, deficit=True) for pair in ("P2", "P4") for c in ("C2", "C3") for p in POLICIES]  # D
    labels = [r["label"] for r in runs]
    assert len(labels) == len(set(labels)), "duplicate labels"
    m = {"run_set": "board-grid", "defaults": dict(G.COMMON), "runs": runs}
    out = os.path.join(HERE, "board-grid.yaml")
    with open(out, "w") as fh:
        fh.write("# GENERATED by experiments/matrices/gen_board_grid.py -- do not edit.\n")
        yaml.safe_dump(m, fh, sort_keys=False)
    print(f"wrote {out}: {len(runs)} runs")


if __name__ == "__main__":
    main()
