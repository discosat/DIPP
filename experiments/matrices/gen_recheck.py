#!/usr/bin/env python3
"""Re-check runs for the final policy on the corrected battery (2026-10-19).

    python3 experiments/matrices/gen_recheck.py   -> experiments/matrices/recheck.yaml

The energy-limited board results outside the board grid ran on the float
battery level (METRIC.md addendum 2026-10-18) and with policy v2, before the
energy-timed port; they are re-run here with the final policy:
  C6     interlock recovery: DISCO-2 end of life, start 1 Wh below the
         2-orbit floor, main-s1 x matched; low, med, high, deadline-only,
         final (eval-extra's C6 had low, med, high, v2);
  C7     cost-model error (R3.3): C2 with every latency and energy in the
         seed x0.5 / x2, final policy (not battery-affected; re-run because
         the policy changed since eval-extra);
  smoke  the below-floor smoke run of smoke-final (end of life, start below
         the floor, 40 frames of smoke-v2, clear-sky content).
Run set "recheck": results in runs/recheck/.
"""
import os, sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import gen_eval as G  # noqa: E402


def main():
    env = G.mat.read_env(os.path.join(ROOT, "experiments/platforms/disco2-eol.env"))
    floor = float(env["DIPP_BATT_SURVIVAL_ORBITS"]) * float(env["DIPP_BATT_BUS_W"]) * \
        float(env["DIPP_BATT_ORBIT_MIN"]) / 60
    soc_low = round((floor - 1.0) / float(env["DIPP_BATT_CAPACITY_WH"]), 4)
    runs = []
    for p_ in ("low", "med", "high", "greedy", "adaptive"):
        r = G.run("C6", "1x", "matched", p_, 1)
        r.update(platform="disco2-eol.env", soc0=soc_low)
        if p_ == "adaptive":
            r["label"] = "C6-final-s1"
        runs.append(r)
    for f in ("0.5", "2"):
        r = G.run("C7", "1x", "matched", "adaptive", 1)
        r["label"] = f"C7-final_cost_x{f}-s1"
        r["cost_seed"] = f"cost_x{f}.seed"
        runs.append(r)
    smoke = yaml.safe_load(open(os.path.join(HERE, "smoke-final.yaml")))
    s = dict(smoke["runs"][[r["label"] for r in smoke["runs"]].index("smoke-final-eol-below-floor")])
    for k, v in smoke.get("defaults", {}).items():
        if k not in s and k not in G.COMMON:
            s[k] = v
    s["label"] = "smoke-eol-below-floor"
    runs.append(s)
    labels = [r["label"] for r in runs]
    assert len(labels) == len(set(labels)), "duplicate labels"
    m = {"run_set": "recheck", "defaults": dict(G.COMMON), "runs": runs}
    out = os.path.join(HERE, "recheck.yaml")
    with open(out, "w") as fh:
        fh.write("# GENERATED by experiments/matrices/gen_recheck.py -- do not edit.\n"
                 f"# C6 soc0 = (floor {floor:.2f} Wh - 1 Wh) / capacity. C7 needs cost_x0.5.seed and\n"
                 "# cost_x2.seed on the board (staging/eval-extra/).\n")
        yaml.safe_dump(m, fh, sort_keys=False, width=200)
    print(f"wrote {out}: {len(runs)} runs")


if __name__ == "__main__":
    main()
