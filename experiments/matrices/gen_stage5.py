#!/usr/bin/env python3
"""Write the Stage 5 campaign matrices from the traces' own headers.

    python3 experiments/matrices/gen_stage5.py      # after experiments/traces/make_traces.sh

Every trace run's phase0 is the trace's (campaign.py refuses any other) and
its soc0 is the platform's periodic steady state at that phase
(tools/make_arrival_trace.py steady_soc: the bus load, plus the idle board
when the platform keeps it on), perturbed only where a matrix says so. So a
change of trace, profile or platform is picked up by re-running this, never
by editing numbers.

Matrices (each run ~1 h on the main trace; the pilot fixes the order):
  pilot          adaptive on main-s1: duration, behaviour, the parser on real data
  table7-core    5 policies x main-s{1,2,3}, board per burst            15 runs
  arm-board      5 policies x main-s{1,2,3}, board always on            15
  arm-load       5 policies x {eg, con, poi3, poi76}                    20
  arm-reserve    adaptive x reserve {0, 0.05} x main-s{1,2,3}            6
                 (0.02 is table7-core)
  arm-eol        {adaptive, low, high} x main-s{1,2,3} at end of life     9
  fig-sensitivity {adaptive, low, high} x soc0 {steady -0.03, steady, +0.03}
                 x urgent {0, ~10, ~50 %} on main seed 1                 27
"""
import os, sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import make_arrival_trace as mat  # noqa: E402

TR = "experiments/traces"
POLICIES = {"adaptive": 1, "low": 2, "medium": 6, "high": 3, "monolith": 4}
COMMON = {
    "storage": "HYBRID", "heuristic": "BEST_EFFORT", "load": "trace", "images": 1,
    "cost_seed": "cost.seed", "image_prefix": "cs12_test_matched_",
    # feed_trace.sh: quiescent 5 s before a fast-forward; 60 s chunks, 0.5 s
    # apart (energy-halted batches resume between chunks); after the last
    # frame up to one orbit of fast-forward for a halted backlog.
    # run.sh drains on completions; min_drain is the stall limit (a backlog
    # still halted after the tail ends the run after this long, unfinished).
    "min_drain": 150,
    # scheduling policy (src/include/sched_policy.h): the rule's thresholds
    # (k = 2), stage-boundary yielding, the original gates
    "sched_q_med": 12, "sched_q_low": 20, "sched_granularity": "stage",
    "sched_gate_med_ms": 5000, "sched_gate_low_ms": 3000,
    "idle_window": 5, "ff_chunk": 60, "ff_tick": 0.5, "tail_ff": 5726,
}


def header(trace, key):
    for ln in open(os.path.join(ROOT, trace)):
        if ln.startswith(f"# {key}="):
            return float(ln.split("=", 1)[1])
    raise SystemExit(f"{trace}: no '# {key}=' header -- run experiments/traces/make_traces.sh")


def steady(platform, phase0):
    env = mat.read_env(os.path.join(ROOT, "experiments/platforms", platform))
    prof = mat.read_profile(os.path.join(ROOT, "analysis/power-profile", env["DIPP_BATT_PROFILE"]))
    return round(mat.steady_soc(env, prof, phase0), 4)


def run(label, policy, trace, platform="disco2-bol.env", dsoc=0.0):
    ph = header(trace, "phase0")
    soc = min(1.0, round(steady(platform, ph) + dsoc, 4))
    return {"label": label, "pipeline": POLICIES[policy], "arrivals": trace,
            "platform": platform, "phase0": round(ph, 4), "soc0": soc}


def write(name, runs, note):
    m = {"run_set": name, "defaults": dict(COMMON), "runs": runs}
    p = os.path.join(ROOT, "experiments/matrices", f"{name}.yaml")
    with open(p, "w") as fh:
        fh.write(f"# GENERATED by experiments/matrices/gen_stage5.py -- do not edit; re-run it.\n# {note}\n")
        yaml.safe_dump(m, fh, sort_keys=False, width=200)
    print(f"{name}: {len(runs)} runs -> {p}")


def main():
    seeds = (1, 2, 3)
    main_t = {s: f"{TR}/main-s{s}.trace" for s in seeds}
    write("pilot", [run("pilot-adaptive-main-s1", "adaptive", main_t[1])],
          "one adaptive run on the main trace: duration, halts, the parser on real data")
    write("table7-core", [run(f"t7-{p}-s{s}", p, main_t[s]) for p in POLICIES for s in seeds],
          "Table VII: 5 policies x 3 target scatters, S2A global land 2026-10-04 bursts 5-6, board per burst")
    write("arm-board", [run(f"board-{p}-s{s}", p, main_t[s], "disco2-bol-always.env") for p in POLICIES for s in seeds],
          "board-mode arm: as table7-core with the board powered throughout")
    write("arm-load", [run(f"load-{p}-{t}", p, f"{TR}/{t}.trace") for p in POLICIES
                       for t in ("eg", "con", "poi3", "poi76")],
          "workloads: East Greenland (discussion), constellation (stress), Poisson 3 s (stress), Poisson at the S2A mean rate (no bursts)")
    write("arm-reserve", [run(f"reserve{r}-adaptive-s{s}", "adaptive", main_t[s], f"disco2-bol-{r}.env")
                          for r in ("r0", "r05") for s in seeds],
          "reserve arm r in {0, 0.05}; 0.02 is table7-core")
    write("arm-eol", [run(f"eol-{p}-s{s}", p, main_t[s], "disco2-eol.env") for p in ("adaptive", "low", "high")
                      for s in seeds],
          "end of life: 15.257 W delivered")
    sens = []
    for p in ("adaptive", "low", "high"):
        for dname, d in (("lo", -0.03), ("st", 0.0), ("hi", 0.03)):
            for u, t in (("u0", f"{TR}/main-urgent0-s1.trace"), ("u10", main_t[1]), ("u50", f"{TR}/main-urgent265-s1.trace")):
                sens.append(run(f"sens-{p}-soc{dname}-{u}", p, t, dsoc=d))
    write("fig-sensitivity", sens, "start charge (steady state -0.03/0/+0.03) x urgent fraction (0/~10/~50 %), seed 1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
